  /**
   * Validates the component's DOM elements, selectors, classes, durations, delays, and options.
   *
   * Error names match the constructor options where possible.
   *
   * @protected
   *
   * @return {boolean} - The result of the validation checks.
   */
  _validate() {
    this._errors = [];
    this._valid = true;

    this._dispatchEvent("prevalidate", this.rootDOMElement);

    // _rootDOMElement check.
    const rootDOMElementCheck = hasValidRootDOMElement(this, {
      shouldThrow: false,
    });

    // Handle _rootDOMElement check failure.
    if (!rootDOMElementCheck.status) {
      this._errors = [...this._errors, ...rootDOMElementCheck.errors];
      this._valid = false;
    }

    // DOM checks.
    if (Object.keys(this._dom).length > 0) {
      const domElements = {};

      // Loop through and add "Element" to the end of each key in _dom.
      for (const domKey of Object.keys(this._dom)) {
        // If we're dealing with an array, we need to check each element in the array.
        if (Array.isArray(this._dom[domKey])) {
          this._dom[domKey].forEach((element, index) => {
            domElements[`${domKey}Element[${index}]`] = element;
          });
        } else if (this._dom[domKey] !== null) {
          domElements[`${domKey}Element`] = this._dom[domKey];
        }
      }

      // Check the DOM elements.
      const domChecks = isValidInstance(HTMLElement, domElements, {
        shouldThrow: false,
      });

      // Handle DOM check failure.
      if (!domChecks.status) {
        this._errors = [...this._errors, ...domChecks.errors];
        this._valid = false;
      }
    }

    // Query selector checks.
    if (Object.keys(this._selectors).length > 0) {
      const querySelectors = {};

      // Loop through and add "Selector" to the end of each key in _selectors.
      for (const querySelector of Object.keys(this._selectors)) {
        // An empty selector leaves that element type unused.
        if (this._selectors[querySelector] !== "") {
          querySelectors[`${querySelector}Selector`] =
            this._selectors[querySelector];
        }
      }

      // Check the query selectors.
      const querySelectorChecks = isQuerySelector(querySelectors, {
        shouldThrow: false,
      });

      // Handle query selector check failure.
      if (!querySelectorChecks.status) {
        this._errors = [...this._errors, ...querySelectorChecks.errors];
        this._valid = false;
      }
    }

    // Class list checks.
    if (Object.keys(this._classes).length > 0) {
      const classes = {};

      // Loop through and add "Class" to the end of each key in _classes.
      for (const className of Object.keys(this._classes)) {
        if (this._classes[className] === "") {
          continue;
        }

        classes[`${className}Class`] = this._classes[className];
      }

      // Check the class lists.
      const classListChecks = isValidClassList(classes, { shouldThrow: false });

      // Handle class list check failure.
      if (!classListChecks.status) {
        this._errors = [...this._errors, ...classListChecks.errors];
        this._valid = false;
      }
    }

    // Duration checks.
    if (Object.keys(this._durations).length > 0) {
      const durations = {};

      // Loop through and add "Duration" to the end of each key in _durations.
      for (const durationName of Object.keys(this._durations)) {
        durations[`${durationName}Duration`] = this._durations[durationName];
      }

      // Check the durations.
      const durationChecks = isValidType("number", durations, {
        shouldThrow: false,
      });

      // Handle duration check failure.
      if (!durationChecks.status) {
        this._errors = [...this._errors, ...durationChecks.errors];
        this._valid = false;
      }
    }

    // Delay checks.
    if (Object.keys(this.delays).length > 0) {
      const delays = {};

      // Loop through and add "Delay" to the end of each key in delays.
      for (const delayName of Object.keys(this.delays)) {
        delays[`${delayName}Delay`] = this.delays[delayName];
      }

      // Check the delays.
      const delayChecks = isValidType("number", delays, { shouldThrow: false });

      // Handle delay check failure.
      if (!delayChecks.status) {
        this._errors = [...this._errors, ...delayChecks.errors];
        this._valid = false;
      }
    }

    // String checks.
    const strings = {
      _name: this._name,
      _scope: this._scope,
      _eventPrefix: this._eventPrefix,
      _storageKey: this._storageKey,
      key: this._key,
      prefix: this._prefix,
    };

    this._protectedDOMElements.forEach((elementType) => {
      strings[`_protectedDOMElementType[${elementType}]`] = elementType;
    });
    // Check the strings.
    const stringChecks = isValidType("string", strings, { shouldThrow: false });

    // Handle string check failure.
    if (!stringChecks.status) {
      this._errors = [...this._errors, ...stringChecks.errors];
      this._valid = false;
    }

    // Boolean checks.
    const booleans = {
      _shouldStore: this._shouldStore,
    };

    // Check the booleans.
    const booleanChecks = isValidType("boolean", booleans, {
      shouldThrow: false,
    });

    // Handle boolean check failure.
    if (!booleanChecks.status) {
      this._errors = [...this._errors, ...booleanChecks.errors];
      this._valid = false;
    }

    this._dispatchEvent("validate", this.rootDOMElement);

    this._dispatchEvent("postvalidate", this.rootDOMElement);

    return this._valid;
  }

  /**
   * Generates a key for the component.
   *
   * @param {boolean} [regenerate = false] - A flag to determine if the key should be regenerated.
   */
  _generateKey(regenerate = false) {
    if (this._key === "" || regenerate) {
      this._key = Math.random()
        .toString(36)
        .replace(/[^a-z]+/g, "")
        .substring(0, 10);
    }
  }

